print("=== Perulangan for (range) ===")
for angka in range(1, 6):
    print("Angka ke-", angka)

print("\n=== Perulangan for pada list ===")
buah = ["apel", "mangga", "jeruk"]
for item in buah:
    print("Buah:", item)

print("\n=== Perulangan while ===")
hitung = 3
while hitung > 0:
    print("Hitung mundur:", hitung)
    hitung -= 1