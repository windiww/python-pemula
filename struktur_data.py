# List (bisa diubah / mutable)
daftar_modul = ["Variabel", "Operator", "Percabangan", "Perulangan"]
daftar_modul.append("Struktur Data")
print("List modul:", daftar_modul)
print("Modul pertama:", daftar_modul[0])

# Tuple (tidak bisa diubah / immutable)
koordinat = (-6.2, 106.8)
print("Tuple koordinat:", koordinat)

# Dictionary (pasangan key dan value)
profil = {
    "nama": "Budi",
    "platform": "Santrikoding",
    "level": "Pemula"
}
print("Dictionary profil:", profil)
print("Nama:", profil["nama"])